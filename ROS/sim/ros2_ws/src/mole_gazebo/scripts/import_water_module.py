#!/usr/bin/env python3
"""Turn the water module's CAD meshes into light Gazebo meshes for the MOLE model.

Input: the `watermodule` package from branch manan (ROS/watermodule.zip), i.e. the folder
that holds urdf/water_module.urdf and meshes/water_module/water_module_part_NN.stl.
Output (module axes, metres, in models/mole_quad/meshes/water_module/):

    <group>.stl            simplified visual mesh per group of CAD parts (see GROUPS)
    <group>_hull.stl       convex hull of a group, used for collision (DART handles convex meshes well)

Run from the package directory, with numpy, scipy and fast-simplification installed:

    python3 scripts/import_water_module.py /path/to/watermodule/ros2_ws/src/emsd_drone_description

Re-run gen_model.py afterwards. Part identities come from the STEP product names and the
part geometry (sizes, positions); the CAD itself only numbers the solids.
"""
import re
import struct
import sys
from pathlib import Path

import numpy as np
import fast_simplification
from scipy.spatial import ConvexHull

PKG = Path(__file__).resolve().parents[1]
OUT = PKG / 'models/mole_quad/meshes/water_module'

# group: (CAD parts, target triangle count for the visual, make a collision hull)
GROUPS = {
    'tank':          (['00', '01', '03'], 6000, True),   # floor + servo brackets, walls, lid: one sealed box
    'cap':           (['02'], 400, False),
    'servos':        (['04', '05', '06', '07', '08', '09', '10', '11', '12', '13'], 3000, False),  # 2 x MG90S
    'servo_links':   (['16', '17'], 800, False),          # servohorn attachments
    'valve_left':    (['14'], 4000, True),                # Ball Valve V2 housing (funnel), +y side
    'valve_right':   (['15'], 4000, True),                # -y side
    'ball_left':     (['18'], 1500, False),               # hollow valve ball
    'ball_right':    (['19'], 1500, False),
}


def read_stl(path):
    b = path.read_bytes()
    n = struct.unpack('<I', b[80:84])[0]
    if 84 + 50 * n == len(b):
        a = np.frombuffer(b[84:], dtype=np.dtype([('n', '<3f4'), ('v', '<9f4'), ('x', '<u2')]), count=n)
        return a['v'].reshape(-1, 3, 3).astype(float)
    v = [list(map(float, l.split()[1:4])) for l in b.decode().splitlines() if l.strip().startswith('vertex')]
    return np.array(v).reshape(-1, 3, 3)


def write_stl(path, tris):
    tris = np.asarray(tris, np.float32)
    n = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    n /= np.maximum(np.linalg.norm(n, axis=1, keepdims=True), 1e-12)
    rec = np.zeros(len(tris), dtype=np.dtype([('n', '<3f4'), ('v', '<9f4'), ('x', '<u2')]))
    rec['n'], rec['v'] = n, tris.reshape(-1, 9)
    path.write_bytes(b'MOLE water module, generated by import_water_module.py'.ljust(80, b' ')
                     + struct.pack('<I', len(tris)) + rec.tobytes())


def simplify(tris, target):
    pts, idx = np.unique(tris.reshape(-1, 3).round(7), axis=0, return_inverse=True)
    faces = idx.reshape(-1, 3)
    if len(faces) <= target:
        return tris
    for agg in (7, 10, 14, 20):     # raise aggressiveness until the target is met
        p2, f2 = fast_simplification.simplify(pts.astype(np.float32), faces.astype(np.int32),
                                              1 - target / len(faces), agg=agg)
        if len(f2) <= 1.2 * target:
            return p2[f2]
    # CAD meshes that are not manifold stall the simplifier: fall back to vertex clustering
    # (snap to a grid, drop collapsed triangles), growing the cell until the target is met.
    tris = p2[f2]
    for cell in (0.0005, 0.00075, 0.001, 0.0015, 0.002):
        q = np.round(tris / cell) * cell
        keep = (np.linalg.norm(np.cross(q[:, 1] - q[:, 0], q[:, 2] - q[:, 0]), axis=1) > 1e-12)
        q = q[keep]
        if len(q) <= 1.2 * target:
            break
    return q


def main():
    src = Path(sys.argv[1])
    urdf = (src / 'urdf/water_module.urdf').read_text()
    offset = {'00': np.zeros(3)}
    for m in re.finditer(r'<joint name="water_module_part_(\d+)_mount".*?<origin xyz="([^"]+)" rpy="([^"]+)"', urdf, re.S):
        if any(abs(float(a)) > 1e-9 for a in m.group(3).split()):
            raise ValueError(f'part {m.group(1)}: rotated joints are not supported')
        offset[m.group(1)] = np.array([float(a) for a in m.group(2).split()])
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (parts, target, hull) in GROUPS.items():
        tris = np.concatenate([read_stl(src / f'meshes/water_module/water_module_part_{k}.stl') + offset[k] for k in parts])
        vis = simplify(tris, target)
        write_stl(OUT / f'{name}.stl', vis)
        lo, hi = tris.reshape(-1, 3).min(0), tris.reshape(-1, 3).max(0)
        msg = f'{name:12s} parts {",".join(parts):30s} {len(tris):7d} -> {len(vis):5d} tris, ' \
              f'bounds {np.round(lo * 1000, 1).tolist()} .. {np.round(hi * 1000, 1).tolist()} mm'
        if hull:
            # Hull of the simplified mesh, then simplified again: a light convex collision shape.
            pts = np.unique(vis.reshape(-1, 3).round(6), axis=0)
            h = ConvexHull(pts)
            hull_tris = simplify(pts[h.simplices], 400)
            write_stl(OUT / f'{name}_hull.stl', hull_tris)
            h = type('H', (), {'simplices': hull_tris})
            msg += f', hull {len(h.simplices)} tris'
        print(msg)
    print(f'Wrote {OUT}')


if __name__ == '__main__':
    main()
